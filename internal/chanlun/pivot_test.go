// 构造一个"上涨 → 下跌 → 上涨"的三笔结构，验证笔中枢形成。
func TestPivot_Form(t *testing.T) {
	e := NewEngine(Config{})
	klines := []types.Kline{
		// 下跌 0..2，底分型 MK2 价=10
		mk(0, 14, 12, 13),
		mk(1, 13, 11, 12),
		mk(2, 12, 10, 11),
		// 上涨 3..8，顶分型 MK8 价=30
		mk(3, 14, 11, 13),
		mk(4, 18, 14, 17),
		mk(5, 22, 17, 21),
		mk(6, 26, 21, 25),
		mk(7, 28, 24, 27),
		mk(8, 30, 26, 29),
		// 下跌 9..14，底分型 MK14 价=18
		mk(9, 28, 24, 25),
		mk(10, 26, 22, 23),
		mk(11, 24, 20, 21),
		mk(12, 22, 19, 20),
		mk(13, 20, 18.5, 19),
		mk(14, 19, 18, 18.5),
		// 上涨 15..20，顶分型 MK20 价=29
		mk(15, 21, 18.6, 20),
		mk(16, 23, 20, 22),
		mk(17, 25, 22, 24),
		mk(18, 27, 24, 26),
		mk(19, 28, 25, 27),
		mk(20, 29, 26, 28),
		// 右侧确认 21..23
		mk(21, 27, 23, 24),
		mk(22, 25, 21, 22),
		mk(23, 23, 19, 20),
	}
	feedAll(e, klines)

	bis := e.Bis()
	var confirmed []Bi
	for _, b := range bis {
		if b.Confirmed {
			confirmed = append(confirmed, b)
		}
	}
	if len(confirmed) < 3 {
		t.Fatalf("期望至少 3 条已确认笔, got %d; bis=%+v", len(confirmed), bis)
	}

	pivots := e.Pivots()
	if len(pivots) == 0 {
		t.Fatalf("期望至少 1 个中枢, got 0; bis=%+v", confirmed)
	}
	p := pivots[0]
	if p.High <= p.Low {
		t.Errorf("中枢区间应 High > Low, got High=%v Low=%v", p.High, p.Low)
	}
	// 三笔的交集：High = min(30, 30, 29) = 29, Low = max(10, 18, 18) = 18
	if p.High != 29 || p.Low != 18 {
		t.Errorf("中枢区间错: got [%v, %v], want [18, 29]", p.Low, p.High)
	}
	if len(p.BiIdxs) < 3 {
		t.Errorf("中枢应至少包含 3 笔, got %d", len(p.BiIdxs))
	}
}

// 三笔无重叠时不应形成中枢。
func TestPivot_NoOverlap(t *testing.T) {
	_ = NewEngine(Config{})
	// 三笔：低 10 → 高 30 → 低 25 → 高 40 → 低 35 → 高 50
	// 笔1 [10,30], 笔2 [25,30], 笔3 [25,40], 笔4 [35,40], 笔5 [35,50]
	// 三笔（笔1/2/3）交集 = [max(10,25,25), min(30,30,40)] = [25,30] 有重叠... 不行
	// 改成单边凌厉拉升：每段往上走，回调不深。
	// 笔1 5→50, 笔2 50→48, 笔3 48→100, 笔4 100→98, 笔5 98→200
	// 笔1[5,50], 笔2[48,50], 笔3[48,100]: 交集 [max(5,48,48), min(50,50,100)] = [48,50] 还是有重叠
	// 缠论里其实"三笔重叠就形成中枢"是默认假设，绝大多数行情都会成中枢。
	// 真正"无重叠"需要构造连续单边走势。这里我们让笔之间完全不沾边：
	// 笔1 0→10，笔2 10→8（小回），笔3 8→20，笔4 20→18，笔5 18→30
	// 笔1[0,10], 笔3[8,20], 笔5[18,30]：交集 = [max(0,8,18), min(10,20,30)] = [18,10] → 18 > 10, 无交集
	// 但相邻三笔（笔1/2/3）= [max(0,8,8), min(10,10,20)] = [8,10] 有交集 → 还是会形成中枢...

	// 结论：缠论默认三笔重叠就是中枢。要"无重叠"必须连续 3 笔都创新极值且回调不及上一笔。
	// 暂跳过此场景的精确验证。
	t.Skip("缠论中三笔不重叠极少见，需要刻意构造单边行情，留作非核心场景")
}
